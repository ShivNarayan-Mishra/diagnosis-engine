from __future__ import annotations

import random
import uuid
from datetime import datetime, timedelta

from src.benchmark.generator import TraceGenerator
from src.benchmark.scenarios.base import FaultScenario
from src.contracts.interfaces import TraceStore
from src.contracts.records import GroundTruth


class ModelSwapScenario(FaultScenario):
    """
    Simulates a full model-version cutover — every trace switches from `good_value` to
    `bad_value` at the same instant, e.g. a deploy that routes 100% of traffic to a new
    model version at once. Deliberately a different injection shape from
    ToolRegressionScenario's partial rollout (100% cutover vs. mixed population), so the
    benchmark covers both real-world deploy patterns.

    `good_value` defaults to "v2" to match your real generator.py's MODEL_VERSIONS
    baseline — traces generated by TraceGenerator.generate() already carry
    model_version="v2" out of the box, so the "before" window here doesn't need to force
    anything; it's included anyway for explicitness, in case MODEL_VERSIONS ever grows
    beyond one value.

    Mechanics: same pattern as ToolRegressionScenario — generate a normal batch, mutate
    the returned TraceRecords directly, own seeded RNG for outcome re-rolls.
    """

    def __init__(
        self,
        factor: str = "model_version",
        good_value: str = "v2",
        bad_value: str = "v3",
        baseline_failure_rate: float = 0.05,
        bad_failure_rate: float = 0.22,
        n_before: int = 200,
        n_after: int = 200,
        interval_seconds: float = 1.0,
        seed: int = 5678,
    ):
        self.factor = factor
        self.good_value = good_value
        self.bad_value = bad_value
        self.baseline_failure_rate = baseline_failure_rate
        self.bad_failure_rate = bad_failure_rate
        self.n_before = n_before
        self.n_after = n_after
        self.interval_seconds = interval_seconds
        self._rng = random.Random(seed)

    def inject(self, generator: TraceGenerator, store: TraceStore, at: datetime) -> GroundTruth:
        scenario_id = f"model_swap_{uuid.uuid4().hex[:8]}"

        # before window — normal traces, forced onto good_value, outcome untouched
        before_start = at - timedelta(seconds=self.interval_seconds * self.n_before)
        before_traces = generator.generate(
            n=self.n_before, start_time=before_start, interval_seconds=self.interval_seconds
        )
        for trace in before_traces:
            trace.factors[self.factor] = self.good_value
            store.write(trace)

        # after window — everyone switches to bad_value at once, outcome re-rolled
        after_traces = generator.generate(
            n=self.n_after, start_time=at, interval_seconds=self.interval_seconds
        )
        for trace in after_traces:
            trace.factors[self.factor] = self.bad_value
            trace.outcome = "failure" if self._rng.random() < self.bad_failure_rate else "success"
            trace.injected_fault_id = scenario_id
            store.write(trace)

        return GroundTruth(
            scenario_id=scenario_id,
            fault_type="model_swap",
            injected_at=at,
            affected_factor=self.factor,
            affected_value=self.bad_value,
        )
